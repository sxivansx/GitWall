// Release signing is read from android/keystore.properties (git-ignored) or from
// the environment in CI. Without either, the release build falls back to the
// debug key so a local test build always succeeds.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String): String? =
    keystoreProps.getProperty(key) ?: System.getenv("GITWALL_${key.uppercase()}")

